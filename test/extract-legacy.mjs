/* Builds test/.legacy.mjs: the ORIGINAL stats/strategy functions, lifted
   straight out of the untouched Alpha-Seeker.html, wrapped as an ES module.

   This is the baseline the golden test compares against. It has to come from
   the monolith itself -- the original code only ever ran in a browser inside
   one big script, so there is no other trustworthy reference. */
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = readFileSync(new URL('../legacy/Alpha-Seeker.html', import.meta.url), 'utf8').split('\n');

// Brace-matched ranges, same scan used to build the modules.
const RANGES = [
  [1000,1001],[1002,1017],[1019,1028],[1030,1046],[1048,1070],   // cleanNums..findLevels
  [1072,1084],                                                    // logReturns..computeVol
  [1086,1095],[1096,1101],[1102,1109],[1110,1114],                // reclaim, fitLine, trendlines, computeTA
  [935,944],[945,950],[1246,1253],[1254,1259],                    // calcEMA, calcAvgVol, emaSeries, smaSeries
  [1243,1245],[1260,1283],[1284,1309],[1310,1312],[1313,1325],    // HS_* , setups, profileStock, hsEdgeText, hsPrecision
  [1330,1343],[1344,1370],                                        // calcATR, computeRisk
  [1376,1377],[1378,1383],[1415,1430],                            // EARNINGS_OVERRIDE/EARN_WINDOW, earningsDays, gate
  [1432,1505],                                                    // generateSignals
];
const EXPORTS = ['cleanNums','calcRSIseries','pivotIdx','detectDivergence','findLevels',
  'logReturns','stdev','realizedVol','ewmaVol','skewness','kurtosis','volPercentile','computeVol',
  'detectReclaim','fitLine','trendlines','computeTA','calcEMA','calcAvgVol','emaSeries','smaSeries',
  'profileStock','hsEdgeText','hsPrecision','calcATR','computeRisk','earningsDays','applyEarningsGate',
  'generateSignals','HS_HORIZON','HS_MIN_N','HS_MIN_WIN','HS_SETUPS','EARN_WINDOW','EARNINGS_OVERRIDE'];

const body = RANGES.map(([a,b]) => SRC.slice(a-1,b).join('\n')).join('\n\n');
// applyEarningsGate closes over the global S; give it one the test can drive.
const shim = `export const S = { data:{}, signals:{} };\n`;
writeFileSync(new URL('.legacy.mjs', import.meta.url),
  `/* GENERATED by test/extract-legacy.mjs -- do not edit, do not commit. */\n` +
  shim + body + `\n\nexport { ${EXPORTS.join(', ')} };\n`);
console.log(`test/.legacy.mjs written (${body.split('\n').length} lines from the monolith)`);
